"""Migrate peer runtime columns in PostgreSQL / MySQL via SQLAlchemy Core.

Must run while all WGDashboard instances are stopped. Snapshots contain secrets;
only restore snapshots generated by this tool and stored on trusted storage.
"""

import os
import pickle
import tempfile
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import Column, MetaData, String, Table, create_engine, inspect, insert, select, text
from sqlalchemy.schema import CreateIndex, CreateTable

FIELDS = ("endpoint", "status", "latest_handshake")
PEER_MARKERS = {"id", "private_key", "allowed_ip", "total_receive", "total_sent"}
SUFFIXES = ("_runtime", "_restrict_access", "_deleted", "_transfer", "_history_endpoint")


class MigrationError(Exception):
    pass


def _q(conn, name):
    return conn.dialect.identifier_preparer.quote_identifier(name)


def _interfaces(conn, warnings=None):
    inspector = inspect(conn)
    tables = set(inspector.get_table_names())
    registered = None
    if "ConfigurationsInfo" in tables:
        info_columns = {c["name"] for c in inspector.get_columns("ConfigurationsInfo")}
        if "ID" not in info_columns:
            raise MigrationError("ConfigurationsInfo: missing ID column")
        registered = {row[0] for row in conn.execute(text(
            f"SELECT {_q(conn, 'ID')} FROM {_q(conn, 'ConfigurationsInfo')}"
        ))}
    result = []
    for name in sorted(tables):
        if name.endswith(SUFFIXES):
            continue
        cols = {c["name"] for c in inspector.get_columns(name)}
        if not PEER_MARKERS <= cols:
            continue
        if registered is not None and name not in registered:
            count = conn.execute(text(
                f"SELECT COUNT(*) FROM {_q(conn, name)}"
            )).scalar_one()
            if count == 0:
                if warnings is not None:
                    warnings.append((name, "not in ConfigurationsInfo; 0 peers", True))
                continue
            if warnings is not None:
                warnings.append((name, f"not in ConfigurationsInfo; {count} peers, preserved for migration", False))
        present = set(FIELDS) & cols
        if present and present != set(FIELDS):
            raise MigrationError(f"{name}: incomplete legacy runtime columns: {sorted(present)}")
        runtime = f"{name}_runtime"
        if runtime in tables:
            rt_cols = {c["name"] for c in inspector.get_columns(runtime)}
            if not {"id", *FIELDS} <= rt_cols:
                raise MigrationError(f"{runtime}: invalid runtime schema")
            if present:
                # A previous migration may have been interrupted. Never drop
                # an existing runtime table during automatic recovery.
                raise MigrationError(f"{runtime}: already exists while legacy columns remain; manual recovery required")
        elif not present:
            raise MigrationError(f"{name}: legacy columns absent but runtime table missing")
        result.append((name, bool(present)))
    return result


def _snapshot(conn, names, directory):
    """Persist all original peer tables before any migration DDL."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True, mode=0o700)
    metadata = MetaData()
    records = []
    for name in names:
        table = Table(name, metadata, autoload_with=conn)
        ddl = str(CreateTable(table).compile(dialect=conn.dialect))
        indexes = [str(CreateIndex(idx).compile(dialect=conn.dialect)) for idx in table.indexes]
        rows = [dict(row) for row in conn.execute(select(table)).mappings()]
        records.append({"name": name, "ddl": ddl, "indexes": indexes, "rows": rows})
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    dest = directory / f"peer-runtime-{conn.dialect.name}-{stamp}.snapshot"
    fd, pending = tempfile.mkstemp(prefix='.peer-runtime-', dir=directory)
    try:
        with os.fdopen(fd, 'wb') as file:
            os.fchmod(file.fileno(), 0o600)
            pickle.dump({'dialect': conn.dialect.name, 'tables': records}, file, protocol=4)
            file.flush()
            os.fsync(file.fileno())
        os.replace(pending, dest)
    finally:
        if os.path.exists(pending):
            os.unlink(pending)
    return dest


def _restore_mysql(engine, snapshot):
    # Only snapshots created locally by this tool are trusted. Unpickling
    # modified/untrusted files can execute code.
    with open(snapshot, 'rb') as file:
        state = pickle.load(file)
    if state['dialect'] != engine.dialect.name:
        raise MigrationError('Backup dialect does not match connection')
    with engine.begin() as conn:
        for item in state['tables']:
            conn.execute(text(f"DROP TABLE IF EXISTS {_q(conn, item['name'] + '_runtime')}"))
            conn.execute(text(f"DROP TABLE IF EXISTS {_q(conn, item['name'])}"))
            conn.execute(text(item['ddl']))
            for ddl in item['indexes']:
                conn.execute(text(ddl))
            if item['rows']:
                restored = Table(item['name'], MetaData(), autoload_with=conn)
                conn.execute(insert(restored), item['rows'])
    with engine.connect() as conn:
        for item in state['tables']:
            restored = Table(item['name'], MetaData(), autoload_with=conn)
            result = [dict(r) for r in conn.execute(select(restored)).mappings()]
            if sorted((repr(r) for r in result)) != sorted((repr(r) for r in item['rows'])):
                raise MigrationError(f"{item['name']}: restoration verification failed")


def _verify_rows(conn, main, runtime):
    p = _q(conn, main)
    r = _q(conn, runtime)
    missing = conn.execute(text(f"SELECT COUNT(*) FROM {p} p LEFT JOIN {r} r ON p.id=r.id WHERE r.id IS NULL")).scalar_one()
    orphans = conn.execute(text(f"SELECT COUNT(*) FROM {r} r LEFT JOIN {p} p ON p.id=r.id WHERE p.id IS NULL")).scalar_one()
    if missing or orphans:
        raise MigrationError(f"{main}: runtime row mismatch: missing={missing}, orphans={orphans}")
    if conn.dialect.name == 'postgresql':
        mismatch = ' OR '.join(f'p.{_q(conn, c)} IS DISTINCT FROM r.{_q(conn, c)}' for c in FIELDS)
    else:
        mismatch = ' OR '.join(f'NOT (p.{_q(conn, c)} <=> r.{_q(conn, c)})' for c in FIELDS)
    count = conn.execute(text(f"SELECT COUNT(*) FROM {p} p JOIN {r} r ON p.id=r.id WHERE {mismatch}")).scalar_one()
    if count:
        raise MigrationError(f"{main}: {count} runtime values differ")


def _migrate_one(conn, name):
    main = Table(name, MetaData(), autoload_with=conn)
    rtname = f'{name}_runtime'
    runtime = Table(rtname, MetaData(),
                    Column('id', String(255), primary_key=True, nullable=False),
                    *(Column(c, String(255)) for c in FIELDS))
    runtime.create(conn)
    rows = [dict(r) for r in conn.execute(select(main.c.id, *(main.c[c] for c in FIELDS))).mappings()]
    if rows:
        conn.execute(insert(runtime), rows)
    _verify_rows(conn, name, rtname)
    # Portable across PostgreSQL and MySQL/MariaDB; identifiers are quoted.
    drops = ', '.join(f'DROP COLUMN {_q(conn, c)}' for c in FIELDS)
    if conn.dialect.name == 'postgresql':
        # PostgreSQL accepts multiple DROP COLUMN clauses as well.
        conn.execute(text(f'ALTER TABLE {_q(conn, name)} {drops}'))
    else:
        conn.execute(text(f'ALTER TABLE {_q(conn, name)} {drops}'))
    cols = {c['name'] for c in inspect(conn).get_columns(name)}
    if set(FIELDS) & cols:
        raise MigrationError(f'{name}: legacy columns still present')


def migrate_external(*, dry_run=False, backup_dir='db'):
    from modules.DatabaseConnection import ConnectionString

    engine = create_engine(ConnectionString('wgdashboard'))
    try:
        if engine.dialect.name not in ('postgresql', 'mysql'):
            raise MigrationError(f'Unsupported dialect: {engine.dialect.name}')
        warnings = []
        with engine.connect() as conn:
            interfaces = _interfaces(conn, warnings)
        pending = [name for name, needs in interfaces if needs]
        if dry_run:
            already = [name for name, needs in interfaces if not needs]
            excluded = [(name, reason) for name, reason, skip in warnings if skip]
            print(f'Need migration ({len(pending)}):')
            for name in pending:
                print(f'  - {name}')
            print(f'Already migrated ({len(already)}):')
            for name in already:
                print(f'  - {name}')
            print(f'Skipped unregistered empty tables ({len(excluded)}):')
            for name, reason in excluded:
                print(f'  - {name} (WARNING: {reason})')
            for name, reason, skip in warnings:
                if not skip:
                    print(f'WARNING: {name}: {reason}')
        else:
            for name, reason, _skip in warnings:
                print(f'WARNING: {name}: {reason}')
        if not pending:
            print(f'No migration needed ({len(interfaces)} interface tables checked).')
            return 0
        if not dry_run:
            print(f'Peer runtime migration required ({len(pending)}):')
            for name in pending:
                print(f'  - {name}')
        if dry_run:
            return len(pending)
        # On MySQL, interrupted DDL is not transactional. Never auto-retry a
        # previous incomplete migration; retain its snapshot for recovery.
        marker = Path(backup_dir) / 'peer-runtime-mysql.in-progress'
        if engine.dialect.name == 'mysql' and marker.exists():
            raise MigrationError(f'Interrupted migration marker: {marker}. Restore the saved snapshot before retrying.')
        # A single snapshot covers every interface before the first DDL.
        with engine.connect() as conn:
            snapshot = _snapshot(conn, pending, backup_dir)
        print(f'Peer runtime snapshot: {snapshot}')
        if engine.dialect.name == 'mysql':
            fd = os.open(marker, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            with os.fdopen(fd, 'w') as file:
                file.write(str(snapshot) + '\n')
                file.flush()
                os.fsync(file.fileno())
        try:
            with engine.begin() as conn:
                for name in pending:
                    _migrate_one(conn, name)
        except Exception as exc:
            if engine.dialect.name == 'mysql':
                try:
                    _restore_mysql(engine, snapshot)
                    print('MySQL/MariaDB migration rolled back from snapshot.')
                    marker.unlink()
                except Exception as restore_error:
                    raise MigrationError(
                        f'Migration failed ({exc}); restoration failed ({restore_error}). '
                        f'Snapshot retained at {snapshot}. DO NOT START WGDashboard.'
                    ) from restore_error
            raise MigrationError(f'Migration failed: {exc}. Snapshot retained at {snapshot}') from exc
        if engine.dialect.name == 'mysql':
            marker.unlink()
        print(f'Migration completed: {len(pending)} interface table(s). Snapshot: {snapshot}')
        return len(pending)
    finally:
        engine.dispose()
